#!/usr/bin/env python3
"""Package the local fixes for drresearch into a deterministic zip with a sha256 manifest.

Only code ships: the KAT dumps are regenerated by kat/run_kat.sh, and the 42 GB dump artifacts,
LBA lists and .npy matrices are measurements of one drive, not part of a fix.

Usage:  python make_fix_bundle.py            env: OUT
Writes: the zip beside this file, plus fix_bundle_manifest.txt
"""
import hashlib
import os
import zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.environ.get('OUT', os.path.join(HERE, 'drresearch_fix_bundle_2026-11-16.zip'))
MANIFEST = os.environ.get('MANIFEST', os.path.join(HERE, 'fix_bundle_manifest.txt'))

CODE = [
    'dumpextractrelevant.pl',      # modified: per-page POSFOUND clear + evidence-anchored pass
    'perblock_xor.patch',
    'xorsolve_perblock.py',
    'probe_perblock_k.py',
    'repair_anchors.py',
    'positional_anchors.py',
    'anchor_coverage.py',
    'hard_probe.py',
    'compare_methods.py',
    'finish_after_sweep.py',
    'wait_and_compare.py',
    'lba_owner.py',
    'lba_block_map.py',
    'dup_pages.py',
    'delta_probe.py',
    'certify_data.py',
    'recover_h.py',
    'kat/run_kat.sh',
    'kat/make_corrupt.py',
    'kat/make_hard.py',
    'kat/make_synth_perblock.py',
    'kat/dumpextractrelevant.stock.pl',
    'kat/stock/dumpextractrelevant.pl',
    'kat/stock/xorsearch.pl',
]
SHIM = 'kat/shim/List/MoreUtils.pm'

README = """# drresearch fixes, 2026-11-16

Target: PS2251-11 controller + Toshiba BiCS4 NAND (ID 98 3c 98 b3), 42,042,654,720 B dump,
1,980 blocks x 21,233,664 B, page 18,432 B = 16 x (1024 DATA + 6 SA + 114 ECC).

## What changed in the shipped tool

`dumpextractrelevant.pl`
1. `%posfound` is never cleared per page, so every page was digit-parsed at byte offsets
   marked by OTHER pages: an accidental bit-rot rescue that inflated the count and produced
   ~170 spurious points on a 60-block slice where only 11.9 % of the grid is legitimately
   covered. Now cleared per page; `POSFOUND_LEGACY=1` restores the old behaviour.
2. New `Byte: `-anchored pass: a record is accepted only on evidence - all format bytes
   present AND (arithmetic agreement OR a field needing no repair).

Measured, on the synthetic fixtures in kat/:
- stock 499/512 damaged -> patched 512/512; patched with the legacy flag 112
- clean fixture unchanged at 512
- real 60-block slice: stock 245,760, patched 245,306, independent python 245,590
- full 42 GB dump: Found 2,062,900 Missing 1,485, output 13,600,124,928 B / 737,854 pages,
  which equals the independent python audit to the point

## Per-block XOR key support

`perblock_xor.patch` indexes the key at the absolute page offset instead of
`pagesize * (pagen % pagesperblock)`, so a dump-sized keystream works while a one-block key
still tiles exactly as before. `xorsolve_perblock.py` recovers the key byte per block by a
256-way `|Block#`^k search.

Measured (kat/run_kat.sh):
- static key: stock and patched outputs byte-identical at 99 %
- dynamic per-block key: stock 6 % then "We give up now"; patched 99 % with descrambled
  bytes equal to ground truth
- probe_perblock_k.py on the real dump: 34/41 sampled blocks have anchors and all 34 imply
  key byte 0x00, i.e. this dump has no per-block XOR dynamics

## Anchor recovery beyond exact digit parsing

- `repair_anchors.py`: 3-field majority vote with one-bit repair. Full dump: 2,115,731
  acceptances over 2,051,830 distinct grid points of 2,064,385 (99.3918 %); 1,378 of the 1,485
  previously-unreadable targets recovered; repaired distance min 3 / median 4 / max 6 bits,
  skeleton bits min 0 / median 0 / max 3.
- `positional_anchors.py`: credits an LBA from record shell + block-ladder consensus + digit
  evidence when the digits themselves cannot be read. Dense 30-block sample (600-629):
  122,880 / 122,880 grid slots credited, 0 conflicts, 0 / 34,560 pages off the ladder.
  `KAT=1 python positional_anchors.py` passes, including the control that proves a page whose
  anchors tie must not pick an arbitrary winner.
- `compare_methods.py`: joins the two routes on grid index. On the sample vs the global
  consensus set: 122,105 / 122,880 agree, 775 positional-only (consensus' skeleton<=12 gate),
  0 points that consensus accepted and positional evaluated and refused.
- `anchor_coverage.py`, `hard_probe.py`, `lba_owner.py`, `dup_pages.py`, `delta_probe.py`,
  `certify_data.py`: measurement and attribution tools; `lba_owner.py` brackets each missing
  grid point by its nearest found anchors, so block attribution needs no LBA-to-block
  monotonicity assumption. Result: 1,485 missing in 464 blocks (961 exact, 504 probable).

## Not fixed, and why

`recover_h.py` recovers the parity-check matrix from the dual code of observed codewords, a
1144 B chunk = one codeword of a binary [9152, ~8240] code. Selftest on a synthetic code with
912 known checks: rank 8240, nullity 912, all 912 recovered checks score syndrome-zero 1.0000
on held-out codewords. On the real dump (12,000 chunks): rank 7,056, only 7 checks at 1.0000.
The written content is a known pattern, not random data, so the observed codewords do not span
the code. The hmatrix still comes only from the author's reconstruction service.

## Run

    perl -Ikat/shim/List kat/../dumpextractrelevant.pl <dump> <out> <pattern.xml> <Chip.txt>
    POSFOUND_LEGACY=1 perl dumpextractrelevant.pl ...        # old behaviour
    KAT=1 python positional_anchors.py                        # tier logic selftest
    cd kat && bash run_kat.sh                                 # XOR patch KAT
    python repair_anchors.py                                  # env DUMP, PATTERN, POOL
    python positional_anchors.py                              # env DUMP, XORKEY, TARGETS, OUT
    python compare_methods.py [TABLE [ALLGRID]]
    python make_fix_bundle.py                                 # this archive

perl 5.38.2 here has no List::MoreUtils and system() children do not inherit -I, so set
PERL5LIB to the shim directory when invoking through a wrapper.
"""


def sha256(path):
    h = hashlib.sha256()
    with open(path, 'rb') as f:
        for chunk in iter(lambda: f.read(1 << 20), b''):
            h.update(chunk)
    return h.hexdigest()


def main():
    files = [c for c in CODE if os.path.exists(os.path.join(HERE, c))]
    missing = [c for c in CODE if c not in files]
    if os.path.exists(os.path.join(HERE, SHIM)):
        files.append(SHIM)
    if missing:
        print('SKIPPED (not present): ' + ', '.join(missing))

    rows = []
    for rel in files:
        p = os.path.join(HERE, rel)
        rows.append((rel, os.path.getsize(p), sha256(p)))
    rows.append(('README.md', len(README.encode()), hashlib.sha256(README.encode()).hexdigest()))
    rows.sort()

    with zipfile.ZipFile(OUT, 'w', zipfile.ZIP_DEFLATED) as z:
        for rel, _sz, _d in rows:
            if rel == 'README.md':
                z.writestr(zipfile.ZipInfo(rel, date_time=(1980, 1, 1, 0, 0, 0)), README)
            else:
                zi = zipfile.ZipInfo(rel, date_time=(1980, 1, 1, 0, 0, 0))
                zi.compress_type = zipfile.ZIP_DEFLATED
                with open(os.path.join(HERE, rel), 'rb') as f:
                    z.writestr(zi, f.read())

    # verify from the archive, not from the tree: recompute every member and compare
    bad = []
    with zipfile.ZipFile(OUT) as z:
        names = set(z.namelist())
        for rel, sz, digest in rows:
            data = z.read(rel)
            if hashlib.sha256(data).hexdigest() != digest or len(data) != sz:
                bad.append(rel)
        extra = sorted(names - {r[0] for r in rows})
    if bad or extra:
        raise SystemExit('bundle verify FAILED: %d mismatched, %d unexpected members'
                         % (len(bad), len(extra)))

    with open(MANIFEST, 'w') as f:
        f.write('# sha256  bytes  path  (bundle %s)\n' % os.path.basename(OUT))
        for rel, sz, digest in rows:
            f.write('%s %10d  %s\n' % (digest, sz, rel))
        f.write('%s %10d  %s\n' % (sha256(OUT), os.path.getsize(OUT), os.path.basename(OUT)))

    print('members %d, verified from the archive' % len(rows))
    print('bundle : %s  (%d bytes)' % (OUT, os.path.getsize(OUT)))
    print('sha256 : %s' % sha256(OUT))
    print('manifest: %s' % MANIFEST)
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
